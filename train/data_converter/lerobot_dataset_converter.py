import os
import shutil
import argparse
import pandas as pd
import cv2
import torch
from pathlib import Path
from lerobot.datasets.lerobot_dataset import LeRobotDataset


def convert_to_lerobot(raw_data_dir: str, dataset_repo_id: str, fps: int = 10):
    """
    Converts C++ data collector directories into a LeRobotDataset.

    EXPECTED DIRECTORY STRUCTURE:
    -----------------------------
    raw_data_dir/
    ├── episode_20241026_143000/
    │   ├── metadata.csv
    │   ├── frame_00000.jpg
    │   ├── frame_00001.jpg
    │   └── ...
    ├── episode_20241026_143500/
    │   ├── metadata.csv
    │   ├── frame_00000.jpg
    │   └── ...

    EXPECTED METADATA.CSV FORMAT:
    -----------------------------
    timestamp,frame_id,v_left,v_right,prompt
    1729958400.123,frame_00000.jpg,0.5,0.5,drive to the kitchen
    1729958400.223,frame_00001.jpg,0.5,-0.2,drive to the kitchen
    """
    raw_dir_path = Path(raw_data_dir)

    # 0. Cleanup existing dataset to prevent re-run crashes
    dataset_path = Path.home() / ".cache" / "huggingface" / "lerobot" / dataset_repo_id
    if dataset_path.exists():
        print(
            f"🗑️  Found existing dataset at {dataset_path}. Deleting to prevent crash..."
        )
        shutil.rmtree(dataset_path)

    # 1. Define the LeRobot features schema
    # IMPORTANT: "language_instruction" is removed here. The latest API treats it as a "task",
    # not a standard feature column.
    features = {
        "observation.image": {
            "dtype": "video",
            "shape": (224, 224, 3),
            "names": ["height", "width", "channel"],
        },
        "action": {"dtype": "float32", "shape": (2,), "names": ["v_left", "v_right"]},
    }

    print(f"Initializing LeRobotDataset: {dataset_repo_id}...")
    dataset = LeRobotDataset.create(
        repo_id=dataset_repo_id, fps=fps, features=features, use_videos=True
    )

    # Find all episode directories generated by the C++ node
    episode_dirs = sorted(
        [
            d
            for d in raw_dir_path.iterdir()
            if d.is_dir() and d.name.startswith("episode_")
        ]
    )

    if not episode_dirs:
        print(f"❌ No episode directories found in {raw_data_dir}")
        return

    # Iterate and ingest each episode
    for ep_idx, ep_dir in enumerate(episode_dirs):
        csv_path = ep_dir / "metadata.csv"

        if not csv_path.exists():
            print(f"Skipping {ep_dir.name} - No metadata.csv found.")
            continue

        print(f"Ingesting {ep_dir.name} ({ep_idx + 1}/{len(episode_dirs)})...")

        # Load the CSV generated by the C++ node
        df = pd.read_csv(csv_path)

        for _, row in df.iterrows():
            img_path = ep_dir / row["frame_id"]

            if not img_path.exists():
                print(f"  Warning: Missing image {row['frame_id']}. Skipping frame.")
                continue

            # Load image and convert from BGR (OpenCV default) to RGB (PyTorch default)
            img_bgr = cv2.imread(str(img_path))

            # Sanity check to ensure C++ node did its job
            if img_bgr is None or img_bgr.shape != (224, 224, 3):
                shape = img_bgr.shape if img_bgr is not None else "None"
                print(f"  Warning: Expected 224x224 image, got {shape}. Skipping.")
                continue

            img_rgb = cv2.cvtColor(img_bgr, cv2.COLOR_BGR2RGB)

            # Format to PyTorch tensor: (Channels, Height, Width)
            image_tensor = torch.from_numpy(img_rgb).contiguous()

            # Format actions
            action_tensor = torch.tensor(
                [row["v_left"], row["v_right"]], dtype=torch.float32
            )

            # Extract prompt (handle potential NaNs)
            prompt = str(row["prompt"]) if pd.notna(row["prompt"]) else ""

            # Push to the dataset (Notice: 'prompt' is now passed directly as the 'task' argument)
            dataset.add_frame(
                {
                    "observation.image": image_tensor,
                    "action": action_tensor,
                    "task": prompt,
                }
            )

        # Notify dataset that this contiguous physical run is finished
        dataset.save_episode()

    print(f"\n✅ Success! Dataset saved to: {dataset.root}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Convert raw C++ data logs into a LeRobotDataset."
    )
    parser.add_argument(
        "--raw_dir",
        type=str,
        default=".",
        help="Directory containing the episode folders",
    )
    parser.add_argument(
        "--repo_id", type=str, default="local/my_navigation_bot", help="Dataset repo ID"
    )
    parser.add_argument("--fps", type=int, default=10, help="Camera capture rate in Hz")

    args = parser.parse_args()

    convert_to_lerobot(
        raw_data_dir=args.raw_dir,
        dataset_repo_id=args.repo_id,
        fps=args.fps,
    )
